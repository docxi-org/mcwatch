/**
 * Минимальная длительность состояния загрузки.
 *
 * Локально API отвечает за 2 мс — меньше восьмой части кадра, — и ряд
 * заглушек честно отрисовывался, но исчезал раньше, чем глаз успевал его
 * заметить. Получалось, что подгрузка есть, а признака подгрузки нет.
 *
 * Поэтому карточки ждут, пока заглушки отработают своё: показывать плитки
 * рядом с заглушками, которым уже нечего обещать, было бы враньём.
 *
 * Полсекунды — чтобы переливание успело прочитаться как движение, а не
 * мелькнуть. В прототипе догрузка была подделана таймером на 550 мс ровно
 * затем, чтобы это состояние можно было рассмотреть.
 */
export const MIN_LOADING_MS = 500;

/**
 * Сколько ещё держать заглушки. 0 — ответ и так пришёл не сразу.
 *
 * Результат зажат сверху самим порогом: если часы шагнули назад, разность
 * станет отрицательной, и без ограничения ожидание выросло бы до секунд.
 * Вызывающий сверх того берёт монотонные часы, а не настенные.
 */
export function remainingMs(startedAt: number, now: number, minimum = MIN_LOADING_MS): number {
  return Math.min(minimum, Math.max(0, minimum - (now - startedAt)));
}
