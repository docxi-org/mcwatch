import type { GameListItemDto } from '../api/types.js';

/**
 * Слежение за каталогом на главной. Сервис ходит на Metacritic раз в час, а
 * во время переобработки меняется всё сразу — открытая страница при этом
 * остаётся такой, какой её открыли.
 *
 * Обновляем сами, но не пересоздавая карточки: список отрисован по ключу
 * `slug`, поэтому замена массива не трогает узлы DOM — обложка не моргает, а
 * вставку выше видимой области компенсирует якорение прокрутки браузера.
 */

/** Как часто спрашивать. Сервис меняется раз в час, чаще незачем. */
export const POLL_MS = 60_000;

/** Сколько держать пометку на новой карточке. */
export const FRESH_MS = 6_000;

/**
 * Какие игры появились. Нужны, чтобы пометить их: изменение без движения
 * иначе незаметно — карточки той же высоты просто меняют числа.
 */
export function appearedSlugs(
  before: GameListItemDto[],
  after: GameListItemDto[],
): string[] {
  const known = new Set(before.map((g) => g.slug));
  return after.filter((g) => !known.has(g.slug)).map((g) => g.slug);
}
